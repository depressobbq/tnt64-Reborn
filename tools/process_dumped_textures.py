#!/usr/bin/env python3
"""
process_dumped_textures.py

Decodes raw N64 TMEM texture dumps generated by RT64's `dump_textures = true`
into standard PNG images and builds an `rt64.json` database for HD texture replacement.

Usage:
    python3 tools/process_dumped_textures.py [dumped_dir] [output_dir]

Defaults:
    dumped_dir: ./dumped_textures
    output_dir: ./textures
"""

import sys
import os
import glob
import json
import argparse
from PIL import Image

# Format constants from N64 GBI
G_IM_FMT_RGBA = 0
G_IM_FMT_YUV  = 1
G_IM_FMT_CI   = 2
G_IM_FMT_IA   = 3
G_IM_FMT_I    = 4

G_IM_SIZ_4b   = 0
G_IM_SIZ_8b   = 1
G_IM_SIZ_16b  = 2
G_IM_SIZ_32b  = 3

G_TT_NONE     = 0
G_TT_RGBA16   = 1
G_TT_IA16     = 2

RDP_TMEM_BYTES = 0x1000
RDP_TMEM_PALETTE = 0x800
RDP_TMEM_MASK8 = 0xFFF
RDP_TMEM_MASK16 = 0x7FF

def rgba16_to_rgba(val):
    r = (val >> 11) & 0x1F
    g = (val >> 6) & 0x1F
    b = (val >> 1) & 0x1F
    a = 255 if (val & 1) else 0
    r = (r << 3) | (r >> 2)
    g = (g << 3) | (g >> 2)
    b = (b << 3) | (b >> 2)
    return (r, g, b, a)

def ia16_to_rgba(val):
    i = (val >> 8) & 0xFF
    a = val & 0xFF
    return (i, i, i, a)

def ia8_to_rgba(val):
    i = ((val >> 4) & 0xF) * 17
    a = (val & 0xF) * 17
    return (i, i, i, a)

def ia4_to_rgba(val):
    i = ((val >> 1) & 0x7) * 36
    a = 255 if (val & 1) else 0
    return (i, i, i, a)

def i8_to_rgba(val):
    return (val, val, val, 255)

def i4_to_rgba(val):
    v = (val & 0xF) * 17
    return (v, v, v, 255)

def load_tmem_byte(tmem, rel_addr, mask_addr, or_addr, odd_row, tex_start, stride):
    row_size = max(stride, 1)
    row_start = (rel_addr // row_size) * row_size
    word_idx = (rel_addr - row_start) // 4
    swap_word_idx = word_idx ^ 1
    if odd_row:
        final_addr = tex_start + row_start + (swap_word_idx * 4) + (rel_addr & 3)
    else:
        final_addr = tex_start + rel_addr
    idx = ((final_addr & mask_addr) | or_addr) & RDP_TMEM_MASK8
    return tmem[idx] if idx < len(tmem) else 0

def decode_tmem(tmem_data, tile_info, width, height):
    tile = tile_info.get("tile", {})
    fmt = tile.get("fmt", G_IM_FMT_RGBA)
    siz = tile.get("siz", G_IM_SIZ_16b)
    line = tile.get("line", 0)
    tmem_addr = (tile.get("tmem", 0) << 3) & RDP_TMEM_MASK8
    palette = tile.get("palette", 0)
    stride = line << 3

    tlut_str = tile_info.get("tlut", "None")
    tlut = G_TT_NONE
    if tlut_str == "RGBA16":
        tlut = G_TT_RGBA16
    elif tlut_str == "IA16":
        tlut = G_TT_IA16

    is_rgba32 = (fmt == G_IM_FMT_RGBA and siz == G_IM_SIZ_32b)
    uses_tlut = (tlut != G_TT_NONE)
    tmem_shift = 2 if is_rgba32 else siz
    address_mask = RDP_TMEM_MASK16 if (is_rgba32 or uses_tlut) else RDP_TMEM_MASK8

    img = Image.new("RGBA", (width, height))
    pixels = img.load()

    for y in range(height):
        odd_row = bool(y & 1)
        for x in range(width):
            odd_col = bool(x & 1)
            pixel_addr = y * stride + ((x << tmem_shift) >> 1)
            p0 = load_tmem_byte(tmem_data, pixel_addr, address_mask, 0, odd_row, tmem_addr, stride)
            p1 = load_tmem_byte(tmem_data, pixel_addr + 1, address_mask, 0, odd_row, tmem_addr, stride)

            p_4bit = p0 & 0xF if odd_col else (p0 >> 4) & 0xF

            if uses_tlut:
                if siz == G_IM_SIZ_4b:
                    pal_addr = RDP_TMEM_PALETTE + (palette << 7) + (p_4bit << 3)
                else:
                    pal_addr = RDP_TMEM_PALETTE + (p0 << 3)
                lo = tmem_data[pal_addr & RDP_TMEM_MASK8] if (pal_addr & RDP_TMEM_MASK8) < len(tmem_data) else 0
                hi = tmem_data[(pal_addr + 1) & RDP_TMEM_MASK8] if ((pal_addr + 1) & RDP_TMEM_MASK8) < len(tmem_data) else 0
                pal_val = lo | (hi << 8)
                if tlut == G_TT_RGBA16:
                    pixels[x, y] = rgba16_to_rgba(pal_val)
                else:
                    pixels[x, y] = ia16_to_rgba(pal_val)
            else:
                if siz == G_IM_SIZ_4b:
                    if fmt == G_IM_FMT_IA:
                        pixels[x, y] = ia4_to_rgba(p_4bit)
                    else:
                        pixels[x, y] = i4_to_rgba(p_4bit)
                elif siz == G_IM_SIZ_8b:
                    if fmt == G_IM_FMT_IA:
                        pixels[x, y] = ia8_to_rgba(p0)
                    else:
                        pixels[x, y] = i8_to_rgba(p0)
                elif siz == G_IM_SIZ_16b:
                    val16 = (p0 << 8) | p1
                    if fmt == G_IM_FMT_RGBA:
                        pixels[x, y] = rgba16_to_rgba(val16)
                    else:
                        pixels[x, y] = ia16_to_rgba(val16)
                elif siz == G_IM_SIZ_32b:
                    pixel_addr2 = pixel_addr if is_rgba32 else pixel_addr + 2
                    or_addr = (RDP_TMEM_BYTES >> 1) if is_rgba32 else 0
                    p2 = load_tmem_byte(tmem_data, pixel_addr2, address_mask, or_addr, odd_row, tmem_addr, stride)
                    p3 = load_tmem_byte(tmem_data, pixel_addr2 + 1, address_mask, or_addr, odd_row, tmem_addr, stride)
                    if fmt == G_IM_FMT_RGBA:
                        pixels[x, y] = (p0, p1, p2, p3)
                    else:
                        pixels[x, y] = (p0, p1, p0, p1) if odd_col else (p2, p3, p2, p3)
                else:
                    pixels[x, y] = (255, 255, 255, 255)

    return img

def main():
    parser = argparse.ArgumentParser(description="Decode RT64 dumped TMEM textures to PNG.")
    parser.add_argument("dumped_dir", nargs="?", default="dumped_textures", help="Directory with dumped textures")
    parser.add_argument("output_dir", nargs="?", default="textures", help="Output directory for PNG textures")
    args = parser.parse_args()

    if not os.path.isdir(args.dumped_dir):
        print(f"[!] Directory '{args.dumped_dir}' does not exist.")
        print("    Enable 'dump_textures = true' in settings.ini and play the game to dump textures first.")
        return 1

    os.makedirs(args.output_dir, exist_ok=True)

    tile_files = glob.glob(os.path.join(args.dumped_dir, "*.tile.json"))
    if not tile_files:
        print(f"[!] No *.tile.json files found in '{args.dumped_dir}'.")
        return 1

    print(f"[*] Found {len(tile_files)} texture descriptions in '{args.dumped_dir}'")

    decoded_count = 0
    rt64_hashes = []

    for tile_json_path in sorted(tile_files):
        base_name = os.path.basename(tile_json_path).replace(".tile.json", "")
        tmem_path = os.path.join(args.dumped_dir, base_name + ".tmem")

        if not os.path.exists(tmem_path):
            continue

        try:
            with open(tile_json_path, "r") as f:
                tile_info = json.load(f)
            with open(tmem_path, "rb") as f:
                tmem_data = f.read()
        except Exception as e:
            print(f"[-] Error reading {base_name}: {e}")
            continue

        width = tile_info.get("width", 32)
        height = tile_info.get("height", 32)

        if width <= 0 or height <= 0 or width > 1024 or height > 1024:
            continue

        try:
            img = decode_tmem(tmem_data, tile_info, width, height)
            out_png = os.path.join(args.output_dir, f"{base_name}.png")
            img.save(out_png)
            decoded_count += 1

            clean_hash = base_name.split(".")[0]
            rt64_hashes.append(clean_hash)
        except Exception as e:
            print(f"[-] Failed to decode {base_name}: {e}")

    db = {
        "config": {
            "configurationVersion": 3,
            "autoPath": "rt64",
            "defaultOperation": "stall",
            "defaultShift": "none",
            "hashVersion": 1
        },
        "textures": [{"hashes": {"rt64": h}} for h in sorted(set(rt64_hashes))]
    }

    db_path = os.path.join(args.output_dir, "rt64.json")
    with open(db_path, "w") as f:
        json.dump(db, f, indent=4)

    print(f"[+] Successfully decoded {decoded_count} textures into '{args.output_dir}/'")
    print(f"[+] Created replacement manifest: '{db_path}'")
    print("    You can now upscale or edit any PNG in 'textures/'.")
    print("    The game will automatically load your high-res textures seamlessly on startup!")
    return 0

if __name__ == "__main__":
    sys.exit(main())
